const symbols = ['wasb-symbol', 'wasb-word', 'wasb-latin', 'i-arrow'].map(id => {
  const m = ar.match(new RegExp(`<symbol id="${id}"[\\s\\S]*?</symbol>`));
  if (!m) throw new Error('symbol missing: ' + id);
  return m[0];
}).join('\n  ');
const arrow = '<svg aria-hidden="true"><use href="#i-arrow"/></svg>';
const pad = n => String(n).padStart(2, '0');
function block(b, p, l) {
  const title = b.title && L(b.title, l) ? `<h2 class="blk__title wrap"><span>${esc(L(b.title, l))}</span>${b.type === 'strip' ? `<span class="blk__hint">${esc(t('case.drag', l))}</span>` : ''}</h2>` : '';
  const alt = esc(L(p.name, l) + ' · ' + tags(p, l));
  const img = (s, x = '') => `<img src="${abs(s)}" alt="${alt}" loading="lazy" decoding="async"${x}>`;
  if (b.type === 'full') return `<section class="blk blk--full">${title}<div class="wrap">${img(b.src)}</div></section>`;
  if (b.type === 'grid') return `<section class="blk blk--grid${b.fit === 'contain' ? ' is-contain' : ''}" style="--cols:${+b.cols || 2}">${title}<div class="wrap"><div class="blk__items">${(b.items || []).map(s => img(s)).join('')}</div></div></section>`;
  if (b.type === 'strip') return `<section class="blk blk--strip">${title}<div class="blk__rail" tabindex="0">${(b.items || []).map(s => img(s, ' draggable="false"')).join('')}</div></section>`;
  if (b.type === 'browser') return `<section class="blk blk--browser">${title}<div class="wrap"><div class="browser"><div class="browser__bar"><i></i><i></i><i></i><span>${esc(b.label || '')}</span>${b.url ? `<a href="${esc(b.url)}" target="_blank" rel="noopener">${esc(t('case.visit', l))}${arrow}</a>` : ''}</div><div class="browser__view" tabindex="0">${img(b.src)}</div></div></div></section>`;
  return '';
}
const tile = (p, l) => `<a class="tile" href="${workPath(p.id, l)}" style="--focus:${esc(p.focus || '50% 50%')}" aria-label="${esc(L(p.name, l))}: ${esc(t('plate.open', l))}"><img src="${abs(p.cover)}" alt="${esc(L(p.line, l))}" loading="lazy" decoding="async"><span class="tile__cap"><span class="tile__name">${esc(L(p.name, l))}</span><span class="tile__tags">${esc(tags(p, l))}</span></span><span class="tile__go" aria-hidden="true">${arrow}</span></a>`;

